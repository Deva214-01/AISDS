
import importlib.util
import json
import subprocess
import imageio_ffmpeg
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[3]
EXPERIMENT_DIR = PROJECT_ROOT / "experiments" / "accident_test"


def load_module(module_name, file_path):
    """Load an existing Python engine from its file path."""
    spec = importlib.util.spec_from_file_location(
        module_name, str(file_path)
    )

    if spec is None or spec.loader is None:
        raise RuntimeError(f"Could not load {module_name}")

    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def run_accident_pipeline(video_path, output_dir):
    """
    Run YOLO + ByteTrack V6 and V2 decision engines
    on one uploaded video.
    """
    video_path = Path(video_path).resolve()
    output_dir = Path(output_dir).resolve()

    if not video_path.is_file():
        raise FileNotFoundError(f"Video not found: {video_path}")

    output_dir.mkdir(parents=True, exist_ok=True)

    stem = video_path.stem

    v6_path = EXPERIMENT_DIR / "what_v6.py"
    decision_path = (
        EXPERIMENT_DIR / "accident_decision_engine_v2.py"
    )

    if not v6_path.is_file():
        raise FileNotFoundError(f"V6 engine not found: {v6_path}")

    if not decision_path.is_file():
        raise FileNotFoundError(
            f"Decision engine not found: {decision_path}"
        )

    print("\n========== ACCIDENT PIPELINE ==========")
    print("Input video:", video_path)
    print("Output directory:", output_dir)

    # 1. Load V6 tracking engine.
    tracker = load_module("trafficx_accident_v6", v6_path)

    # 2. Configure uploaded video and output directory.
    tracker.VIDEO_PATH = video_path
    tracker.OUTPUT_DIR = output_dir

    # Calculate candidate time once.
    event_time, event_z_score = tracker.detect_event(video_path)

    original_detect_event = tracker.detect_event

    tracker.detect_event = lambda path: (
        event_time,
        event_z_score
    )

    try:
        print("\nStarting YOLO vehicle tracking...")
        tracker_result = tracker.main()
    finally:
        tracker.detect_event = original_detect_event

    # 3. Expected output files.
    tracks_file = output_dir / f"{stem}_v6_tracks.csv"
    pairs_file = output_dir / f"{stem}_v6_pairs.csv"
    timeline_file = output_dir / f"{stem}_v6_timeline.csv"
    annotated_file = output_dir / f"{stem}_v6.mp4"
    # Convert OpenCV MP4V video to browser-compatible H.264
    if annotated_file.is_file():
        ffmpeg_exe = imageio_ffmpeg.get_ffmpeg_exe()

        h264_file = output_dir / f"{stem}_h264.mp4"

        command = [
            ffmpeg_exe,
            "-y",
            "-i", str(annotated_file),
            "-c:v", "libx264",
            "-preset", "veryfast",
            "-pix_fmt", "yuv420p",
            "-movflags", "+faststart",
            str(h264_file),
        ]

        print("Converting annotated video to H.264...")

        subprocess.run(
            command,
            check=True,
            capture_output=True,
            text=True
        )

        # Replace original output with browser-compatible video.
        h264_file.replace(annotated_file)

    print("H.264 conversion completed:", annotated_file)

    
    

    
    alerts_file = output_dir / f"{stem}_collision_alerts.json"

    required_files = [
        tracks_file,
        pairs_file,
        timeline_file,
    ]

    missing = [
        str(path)
        for path in required_files
        if not path.is_file()
    ]

    if missing:
        raise RuntimeError(
            "Tracking did not generate required files: "
            + ", ".join(missing)
        )

    # 4. Read visual collision alerts generated by V6.
    collision_alerts = []

    if alerts_file.is_file():
        with alerts_file.open("r", encoding="utf-8") as file:
            collision_alerts = json.load(file)

    if not isinstance(collision_alerts, list):
        collision_alerts = []

    print("Visual collision alerts:", len(collision_alerts))

    # 5. Load V2 decision engine.
    decision = load_module(
        "trafficx_accident_decision_v2",
        decision_path
    )

    decision.BASE = output_dir

    print("\nRunning accident decision analysis...")
    decision.analyse(stem, event_time)

    # 6. Read generated V2 report.
    report_file = output_dir / f"{stem}_decision_v2.json"

    if not report_file.is_file():
        raise RuntimeError(
            "Accident decision report was not generated."
        )

    with report_file.open("r", encoding="utf-8") as file:
        report = json.load(file)

    # 7. Add visual collision alerts to the report.
    report["collision_alerts"] = collision_alerts
    report["alert_count"] = len(collision_alerts)

    report["candidate_event_z_score"] = round(
        float(event_z_score), 3
    )

    report["processing_engine"] = (
        "YOLO + ByteTrack + Rule-based V2"
    )

    report["annotated_video_available"] = (
        annotated_file.is_file()
    )

    report["collision_alerts_available"] = alerts_file.is_file()

    # Preserve the original V2 decision status.
    with report_file.open("w", encoding="utf-8") as file:
        json.dump(report, file, indent=4)

    print("\n========== PIPELINE COMPLETED ==========")
    print("Status:", report.get("accident_status"))
    print("Candidate time:", report.get("candidate_time_seconds"))
    print("Visual alerts:", len(collision_alerts))
    print("Report:", report_file)
    print("Annotated video:", annotated_file)

    return {
        "report": report,
        "report_path": str(report_file),
        "annotated_video_path": (
            str(annotated_file)
            if annotated_file.is_file()
            else None
        ),
        "collision_alerts_path": (
            str(alerts_file)
            if alerts_file.is_file()
            else None
        ),
        "tracks_path": str(tracks_file),
        "pairs_path": str(pairs_file),
        "timeline_path": str(timeline_file),
    }
